/* 名前から担当を引く。見つからなければ汎用あつかい（何も足さない） */
function agentByName(name) {
  for (var i = 0; i < AGENTS.length; i++) {
    if (AGENTS[i].name === name) return AGENTS[i];
  }
  return null;
}
